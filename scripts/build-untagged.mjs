#!/usr/bin/env node
// Write UNTAGGED.md: which videos still need a set or product tag.
//
//   node scripts/build-untagged.mjs
//
// This file used to be hand-written, and by the time anyone read it again it
// said "308 videos total, 237 fully tagged" against a catalogue of 312 and 269,
// and listed Japanese sets as untagged that had been tagged for weeks. A
// worklist that is wrong is worse than no worklist: it sends you looking for
// problems that are already fixed and hides the ones that are not.
//
// So it is generated from the same videos.json every page is built from, which
// means it is correct on every build or it is not there at all.
//
// It is a repo document, not a page: nothing under public/ links to it and it
// is never deployed. It exists so the owner can see, in one place, exactly what
// is holding pages out of the index, because an untagged video is deliberately
// noindex and stays out of the sitemap.

import { readFile, writeFile } from "node:fs/promises";
import { dirname, join } from "node:path";
import { fileURLToPath } from "node:url";
import { CARD_SETS, PRODUCT_TYPES } from "../shared/taxonomy.mjs";

const ROOT = join(dirname(fileURLToPath(import.meta.url)), "..");

const { videos } = JSON.parse(await readFile(join(ROOT, "public/data/videos.json"), "utf8"));

let playlists = [];
try {
  playlists = JSON.parse(await readFile(join(ROOT, "public/data/playlists.json"), "utf8")).playlists || [];
} catch {
  /* optional: the report just stops saying which videos are already in one */
}

// Which playlist a video sits in, if any. This is the single most useful column
// here, because the fix for most of these is a playlist title rather than a
// hand-written override: the sync reads playlist titles and tags everything
// inside them. A video already in a playlist needs that playlist RENAMED; a
// video in none needs adding to one.
const playlistOf = new Map();
for (const p of playlists) {
  for (const id of p.videoIds || []) if (!playlistOf.has(id)) playlistOf.set(id, p.title);
}

const tagged = videos.filter((v) => v.sets?.length && v.products?.length);
const noBoth = videos.filter((v) => !v.sets?.length && !v.products?.length);
const noSet = videos.filter((v) => !v.sets?.length && v.products?.length);
const noProduct = videos.filter((v) => v.sets?.length && !v.products?.length);

// Newest first: a recent upload is the one whose tags are worth the most,
// because it is the one the home page and the feeds are showing right now.
const byNewest = (a, b) => String(b.published).localeCompare(String(a.published));

// Escaping for markdown LINK TEXT specifically, which needs far less than
// markdown generally. Only a backslash and an unbalanced bracket can actually
// break a link label; escaping the full punctuation set turns "6 BOXES... and
// STILL No OG Starters?!" into "6 BOXES\.\.\. and STILL No OG Starters?\!",
// which is harder to read than the problem it was avoiding. Titles here are
// emoji-heavy YouTube titles, so legibility is the point.
const mdText = (s) => String(s).replace(/([\\[\]])/g, "\\$1");

const row = (v) => {
  const bits = [
    `\`${v.id}\``,
    String(v.published || "").slice(0, 10),
    typeof v.views === "number" ? `${v.views.toLocaleString("en-US")} views` : null,
  ].filter(Boolean);
  const pl = playlistOf.get(v.id);
  const where = pl ? `in playlist "${mdText(pl)}"` : "_not in any playlist_";
  const has = [
    v.sets?.length ? `sets: ${v.sets.join(", ")}` : null,
    v.products?.length ? `products: ${v.products.join(", ")}` : null,
  ].filter(Boolean).join(", ");
  return `- [${mdText(v.title)}](https://www.youtube.com/watch?v=${v.id})\n  ${[
    bits.join(", "),
    where,
    has || null,
  ].filter(Boolean).join(" \u00b7 ")}`;
};

const section = (title, list, why) =>
  list.length
    ? `\n## ${title} (${list.length})\n\n${why}\n\n${list.slice().sort(byNewest).map(row).join("\n")}\n`
    : `\n## ${title} (0)\n\nNothing here. ${why}\n`;

const pct = videos.length ? Math.round((tagged.length / videos.length) * 100) : 0;

const doc = `# Videos still needing tags

<!-- GENERATED by scripts/build-untagged.mjs. Do not edit by hand: the next
     build overwrites it. Fix the tags, not this file. -->

${videos.length} videos. **${tagged.length} are fully tagged** (${pct}%) and get their own
indexed page. The remaining ${videos.length - tagged.length} still have a page and still show up
in the library and in site search, but the page is marked \`noindex\` and kept
out of the sitemap, because a page with no set and no product is too thin to
rank and would drag the rest down with it.

Tag one and it is promoted on the next build. Nothing else has to change.

## How to fix one

The fastest route is a playlist. The sync reads playlist TITLES and tags every
video inside, so renaming one playlist can tag twenty videos at once. A title
naming both the set and the product does it, the way the existing ones do:
"Perfect Order Booster Bundle Series".

Anything awkward to put in a playlist goes in \`data/overrides.json\`, which
always wins over whatever the tagger worked out:

    { "dQw4w9WgXcQ": { "sets": ["pitch-black"], "products": ["etb"] } }

Sets the tagger knows: ${CARD_SETS.map((s) => s.label).join(", ")}.

Products it knows: ${PRODUCT_TYPES.map((p) => p.label).join(", ")}.
${section(
  "Missing both set and product",
  noBoth,
  "These match no filter at all, so they are worth the most to fix.",
)}${section(
  "Missing the set",
  noSet,
  "The product is known, so these only need the set naming.",
)}${section(
  "Missing the product",
  noProduct,
  "The set is known, so these only need the product naming.",
)}`;

await writeFile(join(ROOT, "UNTAGGED.md"), doc);
console.log(
  `Wrote UNTAGGED.md\n  ${tagged.length} of ${videos.length} fully tagged (${pct}%)\n` +
    `  ${noBoth.length} missing both, ${noSet.length} missing the set, ${noProduct.length} missing the product`,
);
