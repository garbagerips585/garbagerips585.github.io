const slugify = (s) =>
  s
    .toLowerCase()
    .replace(/'/g, "")
    .replace(/[^a-z0-9]+/g, "-")
    .replace(/^-|-$/g, "");

// ---------------------------------------------------------------------------
// The .txt files.
// ---------------------------------------------------------------------------

const OUTDIR = join(ROOT, "public/decks");
// Cleared and rewritten, so an archetype that drops out of the metagame does
// not leave a stale file being linked from nowhere and found by search.
await rm(OUTDIR, { recursive: true, force: true });
await mkdir(OUTDIR, { recursive: true });

// POSITION IS RENUMBERED 1..N AND IS NOT LIMITLESS'S OWN RANK. Their table
// carries an "Other" bucket, which sits 11th by share and is not a deck: it
// cannot be built, downloaded or linked, so sync-decks.mjs drops it. Printing
// the untouched ranks after that left the page running 1 to 10, then 12 to 19,
// under a heading saying eighteen decks, so a reader could only conclude
// something had been quietly withheld. Renumbering changes no order, because
// removing one row from a list sorted by share cannot reorder the rest, and the
// page says the bucket was dropped and why.
const decks = d.decks.map((arch, i) => {
  const list = arch.lists[0];
  const slug = slugify(arch.name);
  return { ...arch, pos: i + 1, slug, list, file: `/decks/${slug}.txt` };
});

for (const deck of decks) {
  // Verbatim, plus the single trailing newline every text file ought to end
  // with. Nothing else. See the header.
  await writeFile(join(OUTDIR, `${deck.slug}.txt`), `${deck.list.text}\n`);
}

// ---------------------------------------------------------------------------
// Picking the cards to show for each deck.
// ---------------------------------------------------------------------------

/**
 * The faces of the deck.
 *
 * Sorted so the Pokemon the ARCHETYPE IS NAMED AFTER come first, then by how
 * many copies are played. Sorting by copies alone puts four Dreepy ahead of the
 * two Dragapult ex the deck is named for and built around, which reads as the
 * wrong picture even though the number is right.
 */
function faces(arch, list, n = 4) {
  const words = arch.name.toLowerCase().split(/\s+/).filter((w) => w.length > 2);
  return list.cards["Pokémon"]
    .map((c) => {
      const name = c.name.toLowerCase();
      const named = words.some((w) => name.includes(w));
      return { ...resolve(c), named, score: (named ? 1000 : 0) + c.qty };
    })
    .filter((c) => c.img)
    .sort((a, b) => b.score - a.score)
    .slice(0, n);
}

const cardImg = (c, cls = "dk-card") => {
  const alt = `${c.name}, ${c.setName || c.set} ${c.number}`;
  const img =
    `<img class="${cls}" src="${c.img}" alt="${esc(alt)}" loading="lazy" decoding="async"` +
    `${imgDims(c.img)} onerror="this.remove()">`;
  return avifPicture(img);
};

// ---------------------------------------------------------------------------
// The visible decklist.
// ---------------------------------------------------------------------------

const SECTIONS = ["Pokémon", "Trainer", "Energy"];

/**
 * The list as readable text.
 *
 * The page shows the whole thing rather than only offering the file, because a
 * reader on a phone may want to READ a deck to decide whether to build it, and
 * a page of download buttons is not an information page. The <pre> also holds
 * the exact text the copy button puts on the clipboard, so there is one copy of
 * the decklist in the markup rather than two that can drift.
 */
function listBlock(deck, i) {
  const cols = SECTIONS.map((sec) => {
    const cards = deck.list.cards[sec] || [];
    if (!cards.length) return "";
    const total = cards.reduce((n, c) => n + c.qty, 0);
    const rows = cards
      .map((c) => {
        const r = resolve(c);
        const label = `<span class="dk-q">${c.qty}</span> ${esc(c.name)}`;
        const code = `<span class="dk-set">${esc(c.set)} ${esc(c.number)}</span>`;
        // Link the row to the set guide when this site has one. This is the
        // cross-linking that stops the page being an orphan: a reader who wants
        // to know what a card costs or what else is in that set is one tap away
        // from a page we already wrote.
        return r.slug
          ? `<li><a href="/sets/${r.slug}.html">${label} ${code}</a></li>`
          : `<li><span class="dk-nolink">${label} ${code}</span></li>`;
      })
      .join("");
    return `<div class="dk-col"><h4>${esc(sec)} <span class="dk-n">${total}</span></h4><ul>${rows}</ul></div>`;
  }).join("");

  return `<div class="dk-cols">${cols}</div>
<details class="dk-raw">
  <summary>Show the raw import text</summary>
  <pre id="dk-text-${i}" class="dk-pre">${esc(deck.list.text)}</pre>
  <div class="dk-acts">
    <button type="button" class="dk-copy" data-target="dk-text-${i}">Copy the list</button>
    <a class="dk-dl" href="${deck.file}" download>Download the .txt</a>
  </div>
</details>`;
}

