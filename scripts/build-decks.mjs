#!/usr/bin/env node
// Build /decks.html plus the .txt decklists it hands out.
//
//   node scripts/build-decks.mjs
//
// Reads data/decks.json (written by scripts/sync-decks.mjs) through
// shared/decks.mjs, which also feeds /top-100-playable.html so the two pages
// cannot print different numbers for the same corpus.
//
// WHAT THE READER CAME FOR. Tim asked for easy to download lists of the best
// custom decks you could make, for the physical game and for TCG Live. The
// useful fact that makes that a real deliverable rather than a page of prose is
// that POKEMON TCG LIVE IMPORTS A DECKLIST BY PASTE. So the page hands over an
// actual working artifact: a .txt file in the exact format the client's deck
// importer takes, and a copy button for the phone case where downloading a text
// file and finding it again is the worst part of the whole job.
//
// THE FILES ARE VERBATIM AND THAT IS THE WHOLE POINT. Every .txt is the export
// string Limitless's own Copy to Clipboard button writes, byte for byte, with
// nothing added. NOTHING MAY EVER BE PREPENDED TO ONE. A friendly header line,
// a url, a "generated by" credit or even a stray blank line at the top is text
// the reader will paste into the importer along with the deck, and the importer
// reads the whole clipboard. A decklist that fails to import is worse than no
// decklist, so the file holds the deck and nothing else, and the attribution
// lives on the page around it where it costs the reader nothing.
//
// THE FORMAT WAS READ OFF A REAL ARTIFACT RATHER THAN REMEMBERED. Section
// headers are "Pokemon:", "Trainer:" and "Energy:" followed by the TOTAL number
// of cards in that section, not the number of distinct lines, which is a thing
// it is easy to get backwards. Card lines are "<qty> <name> <SET> <number>",
// space separated. Sections are separated by one blank line. There is no
// trailing "Total Cards" line in this shape. sync-decks.mjs asserts every list
// sums to exactly 60 before it is allowed into the corpus.
//
// WHAT THE RANKING MEASURES, in one sentence, because this is the claim the
// page lives or dies on: these are the MOST PLAYED decks, ordered by share of
// the recorded field, in ONLINE tournaments played in Pokemon TCG Live on
// Limitless's play platform. They are not paper Regionals, they are not Worlds,
// and "best deck" is a claim this site cannot source and therefore never makes.
// Win rate is printed but never sets the order, and is labelled as the separate
// measurement it is.
//
// LEGALITY IS BY CONSTRUCTION, NOT BY ADJUDICATION. Every list is drawn through
// Limitless's own Standard / 2026 rotation filter, so this builder never
// decides whether a card is legal. The rotation itself is an official Pokemon
// fact and is printed with both of its effective dates and the date we read it,
// because "current format" is a claim with an expiry and a page that says
// "current" without saying current as of when goes stale silently.
//
// NO PULL RATES, NO DROP RATES, NO ODDS, and no link to anything stating them.
// See CLAUDE.md. This is a deckbuilding page and there is no version of "how
// likely are you to open this card" that belongs on it.
//
// NO OUTBOUND LINKS. The sources are named in plain text at the foot instead.
// CLAUDE.md's rule is that every click stays on the site, with five documented
// exceptions, and this page did not need to become a sixth: Limitless is
// credited by name, which is what attribution requires, and a reader who wants
// it can find it. See the note in CLAUDE.md under the outbound rule.
//
// NO BACKTICKS IN COMMENTS IN THIS FILE. The page is one template literal and a
// backtick in a comment closes it.

