#!/usr/bin/env node
/* PAGE-LOCAL CSS OUT OF THE SHARED STYLESHEET, INTO THE PAGES THAT USE IT.
 *
 *     node scripts/split-page-css.mjs           split, and write
 *     node scripts/split-page-css.mjs --check   exit 1 if public/ is not what
 *                                                a split would write
 *
 * WHY, 30 September 2026. ui.css is render blocking on all 1,537 pages, and a
 * site-wide performance review measured 31% of it (about 7.8KB gzipped) as
 * rules that match five pages or fewer: the 30th binder, the show cards, the
 * fake-card guide, the vendor cards. Every reader paid for all of it before
 * first paint. Served stripped, the stylesheet finished 39-46ms sooner and LCP
 * moved by about as much on three page types. The owner: "push all fixes".
 *
 * HOW. Runs after every page builder and before stamp-assets.mjs (build-all).
 *   1. Rebuild the FULL stylesheet from assets-source/ui.css exactly as
 *      build-css.mjs does, so this is repeatable from a clean checkout and
 *      running it twice changes nothing.
 *   2. Count, per built page, which class names it contains (anywhere in the
 *      HTML, inline scripts included, so a class a page script adds counts).
 *   3. A rule is PAGE-LOCAL when every comma group of its selector names at
 *      least one class, no class in it appears in the shared scripts
 *      (app.js, packplayer.js, games.js, which add classes at runtime on pages
 *      this cannot predict), and it can match between 1 and 5 pages. Rules
 *      matching no page stay shared: several are deliberate fallbacks that only
 *      render for some data.
 *   4. public/assets/ui.css gets the rest. Each page that can match a local
 *      rule gets it in a <style data-pcss> directly AFTER the ui.css link, in
 *      the stylesheet's own order and inside its own @media or @supports.
 *
 * THE CASCADE. A moved rule now comes after every shared rule instead of in
 * its old place. Local rules are overwhelmingly the later, more specific
 * overrides of shared components, so this almost always keeps the winner; it
 * was verified rather than assumed, by dumping the computed style of every
 * element and pseudo-element on every affected page at 390, 768 and 1440
 * before and after the split and requiring them identical.
 *
 * RUN IT AFTER A SINGLE BUILDER. A page written by one builder on its own has
 * no <style data-pcss> while ui.css no longer holds its rules, so it looks
 * broken until this runs. build-all does it; check-build.py catches it.
 */
import { readFile, writeFile, readdir } from "node:fs/promises";
import { join, dirname, relative } from "node:path";
import { fileURLToPath } from "node:url";
import { SRC, OUT, strip } from "./build-css.mjs";

const ROOT = join(dirname(fileURLToPath(import.meta.url)), "..");
const PUB = join(ROOT, "public");
const CHECK = process.argv.includes("--check");
const MAX_PAGES = 5;
const BANNER =
  "/*! Garbage Rips 585 - generated by scripts/build-css.mjs.\n" +
  "    EDIT assets-source/ui.css, NOT THIS FILE. Same rules in the same order,\n" +
  "    with the comments stripped; the commented original is the source. */\n";
const PCSS_RE = /<style data-pcss>[\s\S]*?<\/style>/g;
const LINK_RE = /<link[^>]+href="\/assets\/ui\.css[^"]*"[^>]*>/;

/* ------------------------------------------------------------ the parser -- */
function skipStr(css, i) {
  const q = css[i];
  let j = i + 1;
  while (j < css.length && css[j] !== q) j += css[j] === "\\" ? 2 : 1;
  return j + 1;
}
function readPrelude(css, i) {
  let depth = 0;
  while (i < css.length) {
    const c = css[i];
    if (c === '"' || c === "'") { i = skipStr(css, i); continue; }
    if (c === "/" && css[i + 1] === "*") { i = css.indexOf("*/", i + 2) + 2; continue; }
    if (c === "(") depth++;
    else if (c === ")") depth--;
    else if (depth === 0 && (c === "{" || c === ";" || c === "}")) return i;
    i++;
  }
  return i;
}
function matchBrace(css, i) { // i at "{": returns index after matching "}"
  let depth = 0;
  while (i < css.length) {
    const c = css[i];
    if (c === '"' || c === "'") { i = skipStr(css, i); continue; }
    if (c === "/" && css[i + 1] === "*") { i = css.indexOf("*/", i + 2) + 2; continue; }
    if (c === "{") depth++;
    else if (c === "}") { depth--; if (depth === 0) return i + 1; }
    i++;
  }
  return i;
}
const GROUP_AT = /^@(media|supports|container|layer)\b/i;
function parse(css, i, end) {
  const nodes = [];
  while (i < end) {
    while (i < end && /\s/.test(css[i])) i++;
    if (i >= end) break;
    if (css[i] === "/" && css[i + 1] === "*") { const e = css.indexOf("*/", i + 2) + 2; nodes.push({ t: "raw", s: i, e }); i = e; continue; }
    if (css[i] === "}") break;
    const p = readPrelude(css, i);
    const prelude = css.slice(i, p).trim();
    if (css[p] === ";" || p >= end) { nodes.push({ t: "raw", s: i, e: p + 1 }); i = p + 1; continue; }
    const close = matchBrace(css, p);
    if (prelude.startsWith("@")) {
      if (GROUP_AT.test(prelude)) nodes.push({ t: "group", s: i, e: close, prelude, bodyS: p + 1, children: parse(css, p + 1, close - 1) });
      else nodes.push({ t: "raw", s: i, e: close });
    } else nodes.push({ t: "rule", s: i, e: close, sel: prelude });
    i = close;
  }
  return nodes;
}

/* ------------------------------------------------------- selector reading -- */
function splitTop(sel) {
  const out = []; let depth = 0, last = 0;
  for (let i = 0; i < sel.length; i++) {
    const c = sel[i];
    if (c === "(" || c === "[") depth++;
    else if (c === ")" || c === "]") depth--;
    else if (c === "," && depth === 0) { out.push(sel.slice(last, i)); last = i + 1; }
  }
  out.push(sel.slice(last));
  return out.map((s) => s.trim());
}
const CLASS_RE = /\.([A-Za-z_][\w-]*)/g;
const classesIn = (s) => [...s.matchAll(CLASS_RE)].map((m) => m[1]);
/* The classes a comma group REQUIRES on a page for it to match anything:
   :not(...) is an absence and is dropped; :is()/:where() with a list inside
   means any one of several, which this does not model, so such a group is
   declared unknowable and the rule stays shared. */
function required(group) {
  if (/:(is|where)\([^)]*,/.test(group)) return null;
  let g = group, prev;
  do { prev = g; g = g.replace(/:not\([^()]*(\([^()]*\)[^()]*)*\)/g, ""); } while (g !== prev);
  const cls = classesIn(g);
  return cls.length ? cls : null;
}

/* ----------------------------------------------------------------- pages -- */
async function htmlFiles(dir, out = []) {
  for (const e of await readdir(dir, { withFileTypes: true })) {
    const p = join(dir, e.name);
    if (e.isDirectory()) { if (!(dir === PUB && (e.name === "assets" || e.name === "data"))) await htmlFiles(p, out); }
    else if (e.name.endsWith(".html")) out.push(p);
  }
  return out;
}

const full = BANNER + strip(await readFile(SRC, "utf8"));
const tree = parse(full, 0, full.length);

const files = (await htmlFiles(PUB)).sort();
const pages = [];
for (const f of files) {
  const raw = await readFile(f, "utf8");
  const html = raw.replace(PCSS_RE, "");
  /* Comments are not usage. stamp-assets.mjs strips the comments out of every
     inline <style> AFTER this runs, and several of them name classes, so
     counting them made this split and the --check that runs after the stamp
     disagree about which rules are local. Counted without them, both see the
     same page. */
  const bare = html.replace(/<!--[\s\S]*?-->/g, " ").replace(/\/\*[\s\S]*?\*\//g, " ");
  const toks = new Set(bare.match(/[A-Za-z_][\w-]*/g) || []);
  const sets = [];
  for (const m of bare.matchAll(/\sclass="([^"]*)"/g)) {
    const c = m[1].trim().split(/\s+/).filter(Boolean);
    if (c.length > 1) sets.push(c);
  }
  pages.push({ f, raw, html, toks, link: LINK_RE.test(html), sets });
}
const jsToks = new Set();
for (const name of await readdir(join(PUB, "assets"))) {
  if (!name.endsWith(".js")) continue;
  for (const t of (await readFile(join(PUB, "assets", name), "utf8")).match(/[A-Za-z_][\w-]*/g) || []) jsToks.add(t);
}

/* Which pages a rule can match, or null when it stays shared. */
function localPages(sel) {
  if (classesIn(sel).some((c) => jsToks.has(c))) return null;
  const hit = new Set();
  for (const g of splitTop(sel)) {
    const req = required(g);
    if (!req) return null;
    for (let k = 0; k < pages.length; k++) if (req.every((c) => pages[k].toks.has(c))) hit.add(k);
    if (hit.size > MAX_PAGES) return null;
  }
  if (hit.size === 0) return null;
  for (const k of hit) if (!pages[k].link) return null;
  return hit;
}

/* WOULD MOVING IT CHANGE WHO WINS. A moved rule lands after every shared rule,
   so a SHARED rule that came after it in the stylesheet, with the SAME
   specificity, styling the SAME element and an overlapping property, used to
   win and would now lose. Measured before this guard existed: a badge on the
   card shows page and on the home page turned the wrong pink, and five pages
   changed width at 1440. So such a rule stays shared. "The same element" is
   read off the built pages' own class attributes: two classes that appear
   together on one element there, or one class in both selectors. */
function specOf(g) {
  const t = g.replace(/:where\([^)]*\)/g, "").replace(/::?[\w-]+/g, (m) => (m.startsWith("::") || /^:(before|after|first-line|first-letter)$/.test(m) ? " E " : " C "));
  const a = (t.match(/#[\w-]+/g) || []).length;
  const b = (t.match(/\.[\w-]+/g) || []).length + (t.match(/\[[^\]]*\]/g) || []).length + (t.match(/ C /g) || []).length;
  const c = (t.replace(/\[[^\]]*\]|\.[\w-]+|#[\w-]+/g, " ").match(/(^|[\s>+~(])[a-zA-Z][\w-]*/g) || []).length + (t.match(/ E /g) || []).length;
  return a * 10000 + b * 100 + c;
}
function targetClasses(g) {
  const last = g.split(/[\s>+~]+/).filter(Boolean).pop() || "";
  return classesIn(last.replace(/:not\([^)]*\)/g, ""));
}
const FAM = (prop) => {
  const p = prop.trim().toLowerCase().replace(/^-webkit-|^-moz-/, "").replace(/^(max|min)-/, "");
  if (/^(top|right|bottom|left|inset)/.test(p)) return "inset";
  if (/^(width|height|inline-size|block-size)$/.test(p)) return "size";
  return p.split("-")[0];
};
const famsOf = (body) => new Set(body.split(";").map((d) => d.split(":")[0]).filter((x) => x && x.trim()).map(FAM));
const flat = []; // every style rule in order, with its context
(function collect(nodes, ctx) {
  for (const n of nodes) {
    if (n.t === "rule") {
      const body = full.slice(full.indexOf("{", n.s) + 1, n.e - 1);
      flat.push({ n, sel: n.sel, groups: splitTop(n.sel).map((g) => ({ spec: specOf(g), tgt: targetClasses(g) })), fams: famsOf(body) });
    } else if (n.t === "group") collect(n.children, [...ctx, n.prelude]);
  }
})(tree, []);
const flatIndex = new Map(flat.map((r, i) => [r.n, i]));
function coOccur(pageIdx, A, B) {
  for (const a of A) if (B.includes(a)) return true;
  for (const k of pageIdx) for (const set of pages[k].sets) {
    if (A.some((a) => set.includes(a)) && B.some((b) => set.includes(b))) return true;
  }
  return false;
}
/* DECIDED FROM THE BOTTOM UP, because a rule's fate depends on the rules after
   it and whether THEY stay: a later rule that the guard keeps shared still
   sits after a moved one. Walking from the end makes every later decision
   final before an earlier one reads it. */
const decision = new Array(flat.length).fill(null);
for (let i = flat.length - 1; i >= 0; i--) {
  const me = flat[i];
  const hit = localPages(me.sel);
  if (!hit) continue;
  const pageIdx = [...hit];
  let ok = hit;
  for (let j = i + 1; j < flat.length && ok; j++) {
    const s2 = flat[j];
    if (decision[j]) continue; // moves too, and keeps its order after this one
    if (![...me.fams].some((f) => s2.fams.has(f))) continue;
    for (const g of me.groups) {
      for (const h of s2.groups) {
        /* A target with no class (".fk-fig figcaption", "main p") cannot be
           read off class attributes, so equal weight and an overlapping
           property are enough to keep the rule shared. Found by the style
           check: captions on /fake-cards.html and paragraphs on /start.html
           changed max-width at 1440 without it. */
        if (g.spec !== h.spec) continue;
        if (!g.tgt.length || !h.tgt.length || coOccur(pageIdx, g.tgt, h.tgt)) { ok = null; break; }
      }
      if (!ok) break;
    }
  }
  decision[i] = ok;
}
const isLocal = (n) => decision[flatIndex.get(n)];

/* Walk the tree: shared text out, and per page the local rules with their
   @media/@supports chain. */
const perPage = new Map(); // k -> [{ctx:[preludes], text}]
let movedRules = 0;
function walk(nodes, ctx) {
  let out = "";
  let last = null;
  for (const n of nodes) {
    const gap = last === null ? "" : full.slice(last, n.s).replace(/\S/g, "");
    last = n.e;
    if (n.t === "rule") {
      const hit = isLocal(n);
      if (hit) {
        movedRules++;
        for (const k of hit) {
          if (!perPage.has(k)) perPage.set(k, []);
          perPage.get(k).push({ ctx, text: full.slice(n.s, n.e) });
        }
        continue;
      }
      out += (out ? "\n" : "") + full.slice(n.s, n.e);
    } else if (n.t === "group") {
      const inner = walk(n.children, [...ctx, n.prelude]);
      if (inner.trim()) out += (out ? "\n" : "") + `${n.prelude}{\n${inner}\n}`;
    } else {
      out += (out ? "\n" : "") + full.slice(n.s, n.e);
    }
    void gap;
  }
  return out;
}
const shared = walk(tree, []) + "\n";

function serialize(items) {
  // Nest consecutive items that share a context chain.
  let out = "", open = [];
  for (const it of items) {
    let common = 0;
    while (common < open.length && common < it.ctx.length && open[common] === it.ctx[common]) common++;
    while (open.length > common) { out += "}"; open.pop(); }
    while (open.length < it.ctx.length) { out += it.ctx[open.length] + "{"; open.push(it.ctx[open.length]); }
    out += it.text;
  }
  while (open.length) { out += "}"; open.pop(); }
  return out;
}

/* ------------------------------------------------------------- write/check -- */
let bad = [];
const current = await readFile(OUT, "utf8").catch(() => "");
if (current !== shared) bad.push(relative(ROOT, OUT));
const writes = [];
for (let k = 0; k < pages.length; k++) {
  const p = pages[k];
  const items = perPage.get(k);
  let next = p.html;
  if (items) next = next.replace(LINK_RE, (m) => `${m}<style data-pcss>${serialize(items)}</style>`);
  if (next !== p.raw) { bad.push(relative(ROOT, p.f)); writes.push([p.f, next]); }
}
if (process.argv.includes("--list")) {
  for (const k of [...perPage.keys()].sort((a, b) => a - b)) console.log(relative(PUB, pages[k].f) + "\t" + perPage.get(k).length);
  process.exit(0);
}
if (CHECK) {
  if (bad.length) {
    console.error(`split-page-css: ${bad.length} file(s) are not what a split would write, e.g. ${bad.slice(0, 3).join(", ")}. Run node scripts/split-page-css.mjs.`);
    process.exit(1);
  }
  console.log("split-page-css: in sync");
} else {
  if (current !== shared) await writeFile(OUT, shared);
  for (const [f, t] of writes) await writeFile(f, t);
  const gz = (await import("node:zlib")).gzipSync;
  console.log(`split-page-css: ${movedRules} rules moved to ${perPage.size} page(s); ui.css ${full.length} -> ${shared.length} bytes, gzip ${gz(full, { level: 9 }).length} -> ${gz(shared, { level: 9 }).length}; ${writes.length} file(s) written`);
}
